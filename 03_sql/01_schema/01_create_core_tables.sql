-- MotoTrack core schema for daily summaries across all study groups.
-- Run in a clean project schema; migrate any older installation before using these scripts.
SET SERVEROUTPUT ON;

CREATE TABLE riders (
    rider_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rider_code  VARCHAR2(50) NOT NULL,
    created_at  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT uq_riders_code UNIQUE (rider_code)
);

CREATE TABLE daily_operations (
    daily_id                  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rider_id                  NUMBER NOT NULL REFERENCES riders(rider_id),
    source_group              VARCHAR2(40) NOT NULL,
    operating_date            DATE NOT NULL,
    distance_km               NUMBER(12,3),
    duration_min              NUMBER(10,2),
    idle_time_min             NUMBER(10,2),
    revenue_kes               NUMBER(14,2),
    maintenance_kes           NUMBER(14,2),
    fuel_cost_kes             NUMBER(14,2),
    fuel_unit_cost_kes_per_l  NUMBER(10,2),
    fuel_amount_l             NUMBER(12,3),
    battery_swap_cost_kes     NUMBER(14,2),
    kwh_charging              NUMBER(12,3),
    created_at                TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT uq_daily_group_date UNIQUE (rider_id, source_group, operating_date),
    CONSTRAINT ck_daily_source_group CHECK (
        source_group IN (
            'BASELINE_FUEL',
            'TRANSITION_CONTROL_FUEL',
            'TRANSITION_TREATMENT_ELECTRIC'
        )
    ),
    CONSTRAINT ck_daily_group_costs CHECK (
        (source_group IN ('BASELINE_FUEL', 'TRANSITION_CONTROL_FUEL')
         AND battery_swap_cost_kes IS NULL AND kwh_charging IS NULL)
        OR
        (source_group = 'TRANSITION_TREATMENT_ELECTRIC'
         AND fuel_cost_kes IS NULL
         AND fuel_unit_cost_kes_per_l IS NULL
         AND fuel_amount_l IS NULL)
    ),
    CONSTRAINT ck_daily_distance CHECK (distance_km IS NULL OR distance_km >= 0),
    CONSTRAINT ck_daily_duration CHECK (duration_min IS NULL OR duration_min >= 0),
    CONSTRAINT ck_daily_idle CHECK (idle_time_min IS NULL OR idle_time_min >= 0),
    CONSTRAINT ck_daily_revenue CHECK (revenue_kes IS NULL OR revenue_kes >= 0),
    CONSTRAINT ck_daily_fuel CHECK (fuel_cost_kes IS NULL OR fuel_cost_kes >= 0),
    CONSTRAINT ck_daily_fuel_unit CHECK (
        fuel_unit_cost_kes_per_l IS NULL OR fuel_unit_cost_kes_per_l >= 0
    ),
    CONSTRAINT ck_daily_fuel_amount CHECK (fuel_amount_l IS NULL OR fuel_amount_l >= 0),
    CONSTRAINT ck_daily_battery CHECK (
        battery_swap_cost_kes IS NULL OR battery_swap_cost_kes >= 0
    ),
    CONSTRAINT ck_daily_kwh CHECK (kwh_charging IS NULL OR kwh_charging >= 0),
    CONSTRAINT ck_daily_maint CHECK (maintenance_kes IS NULL OR maintenance_kes >= 0)
);

CREATE INDEX ix_daily_date ON daily_operations(operating_date);

CREATE TABLE maintenance_events (
    maintenance_event_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rider_id             NUMBER NOT NULL REFERENCES riders(rider_id),
    maintenance_date     DATE NOT NULL,
    maintenance_type     VARCHAR2(60) NOT NULL,
    description          VARCHAR2(500),
    amount_kes           NUMBER(14,2) NOT NULL CHECK (amount_kes >= 0),
    odometer_km          NUMBER(12,3) CHECK (odometer_km IS NULL OR odometer_km >= 0),
    recorded_at          TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX ix_maintenance_rider_date ON maintenance_events(rider_id, maintenance_date);

CREATE TABLE audit_log (
    audit_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_name   VARCHAR2(30) NOT NULL,
    record_key   VARCHAR2(150),
    action_type  VARCHAR2(10) NOT NULL
        CHECK (action_type IN ('INSERT','UPDATE','DELETE')),
    changed_by   VARCHAR2(128) NOT NULL,
    changed_at   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    old_summary  VARCHAR2(1000),
    new_summary  VARCHAR2(1000)
);

CREATE INDEX ix_audit_table_date ON audit_log(table_name, changed_at);

PROMPT MotoTrack core tables created.
