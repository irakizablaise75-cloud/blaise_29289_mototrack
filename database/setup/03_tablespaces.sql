ALTER SESSION SET CONTAINER = i_29289_blaise_mototrack_db;

CREATE TABLESPACE MOTOTRACK_DATA
    DATAFILE SIZE 100M
    AUTOEXTEND ON NEXT 10M MAXSIZE 1G;

CREATE TABLESPACE MOTOTRACK_IDX
    DATAFILE SIZE 50M
    AUTOEXTEND ON NEXT 10M MAXSIZE 500M;

CREATE TEMPORARY TABLESPACE MOTOTRACK_TEMP
    TEMPFILE SIZE 50M
    AUTOEXTEND ON NEXT 10M MAXSIZE 500M;

ALTER USER BLAISE_ADMIN
    DEFAULT TABLESPACE MOTOTRACK_DATA
    TEMPORARY TABLESPACE MOTOTRACK_TEMP
    QUOTA UNLIMITED ON MOTOTRACK_DATA;

ALTER USER BLAISE_ADMIN QUOTA UNLIMITED ON MOTOTRACK_IDX;

SELECT tablespace_name, status, contents
FROM dba_tablespaces
WHERE tablespace_name IN ('MOTOTRACK_DATA', 'MOTOTRACK_IDX', 'MOTOTRACK_TEMP')
ORDER BY tablespace_name;
