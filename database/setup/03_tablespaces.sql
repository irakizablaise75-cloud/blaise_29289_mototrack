-- Run as SYSDBA after 02_create_user.sql in MOTOTRACKPDB.
-- Oracle Managed Files must be configured (DB_CREATE_FILE_DEST).
ALTER SESSION SET CONTAINER = MOTOTRACKPDB;

CREATE TABLESPACE MOTOTRACK_IDX
    DATAFILE SIZE 250M
    AUTOEXTEND ON NEXT 50M MAXSIZE UNLIMITED;

CREATE TEMPORARY TABLESPACE MOTOTRACK_TMP
    TEMPFILE SIZE 200M
    AUTOEXTEND ON NEXT 50M MAXSIZE UNLIMITED;

ALTER USER mototrack QUOTA UNLIMITED ON MOTOTRACK_IDX;
ALTER USER mototrack TEMPORARY TABLESPACE MOTOTRACK_TMP;

SELECT tablespace_name, status, contents
FROM dba_tablespaces
WHERE tablespace_name IN ('MOTOTRACK_DATA', 'MOTOTRACK_IDX', 'MOTOTRACK_TMP')
ORDER BY tablespace_name;
