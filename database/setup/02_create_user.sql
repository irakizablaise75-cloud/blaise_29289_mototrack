-- Run as SYSDBA after opening MOTOTRACKPDB.
-- Oracle Managed Files must be configured (DB_CREATE_FILE_DEST).
ALTER SESSION SET CONTAINER = MOTOTRACKPDB;
ACCEPT mototrack_password CHAR PROMPT 'Enter a password for the MOTOTRACK schema: ' HIDE

CREATE TABLESPACE MOTOTRACK_DATA
    DATAFILE SIZE 500M
    AUTOEXTEND ON NEXT 100M MAXSIZE UNLIMITED;

CREATE USER mototrack IDENTIFIED BY "&mototrack_password"
    DEFAULT TABLESPACE MOTOTRACK_DATA
    TEMPORARY TABLESPACE temp
    QUOTA UNLIMITED ON MOTOTRACK_DATA;

GRANT CREATE SESSION TO mototrack;
GRANT CREATE TABLE TO mototrack;
GRANT CREATE VIEW TO mototrack;
GRANT CREATE PROCEDURE TO mototrack;
GRANT CREATE TRIGGER TO mototrack;

SELECT username, account_status, default_tablespace, temporary_tablespace
FROM dba_users
WHERE username = 'MOTOTRACK';
